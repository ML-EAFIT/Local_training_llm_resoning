"""Heuristic quality filters (Gopher / C4 / FineWeb style) and PII scrubbing.

Each filter returns a rejection reason or None, so the report can show how
much every rule removes per source.
"""
import re

STOP = set("the be to of and a in that have i it for not on with he as you do at this but his by from they we "
           "say her she or an will my one all would there their what so up out if about who get which go me "
           "is are was were has had been can more".split())
BOILER = re.compile(r"(cookie|javascript|lorem ipsum|privacy policy|terms of use|all rights reserved|"
                    r"click here|sign up for|subscribe to our)", re.I)
EMAIL = re.compile(r"\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b")
IPV4 = re.compile(r"\b(?:(?:25[0-5]|2[0-4]\d|1?\d?\d)\.){3}(?:25[0-5]|2[0-4]\d|1?\d?\d)\b")
AUTOGEN = re.compile(r"(auto-?generated|do not edit|generated by)", re.I)
MAX_CHARS = 200_000


def strip_boilerplate(text):
    """Drop short lines that are cookie / nav / legal boilerplate."""
    lines = text.split("\n")
    kept = [ln for ln in lines if not (len(ln) < 200 and BOILER.search(ln))]
    return "\n".join(kept), len(lines) - len(kept)


def scrub_pii(text, ip=True):
    n_email = n_ip = 0
    if "@" in text:
        text, n_email = EMAIL.subn("<EMAIL>", text)
    if ip and "." in text:
        text, n_ip = IPV4.subn("<IP>", text)
    return text, n_email, n_ip


def text_filter(text, source):
    n = len(text)
    if n < 200:
        return "too_short"
    words = text.split()
    nw = len(words)
    if nw < 50:
        return "too_few_words"
    mwl = sum(len(w) for w in words) / nw
    if not 3 <= mwl <= 10:
        return "mean_word_len"
    alpha = sum(c.isalpha() for c in text) / n
    if alpha < (0.45 if source.startswith("math") else 0.6):
        return "low_alpha_ratio"
    if (text.count("#") + text.count("...") + text.count("…")) / nw > 0.1:
        return "symbol_ratio"
    lines = [ln.strip() for ln in text.split("\n") if ln.strip()]
    if lines:
        if sum(ln.endswith(("...", "…")) for ln in lines) / len(lines) > 0.3:
            return "ellipsis_lines"
        if 1 - len(set(lines)) / len(lines) > (0.5 if source.startswith("math") else 0.3):
            return "dup_lines"
    lw = [w.lower() for w in words]
    if sum(w in STOP for w in lw) / nw < 0.06 and not source.startswith("math"):
        return "not_english"
    # repeated n-gram coverage (Gopher): most common bigram covering too many chars
    big = {}
    for a, b in zip(lw, lw[1:]):
        big[(a, b)] = big.get((a, b), 0) + 1
    if big:
        (a, b), c = max(big.items(), key=lambda kv: kv[1])
        if c * (len(a) + len(b)) / max(sum(len(w) for w in lw), 1) > 0.2:
            return "top_bigram"
    return None


def code_filter(text, meta):
    n = len(text)
    if n < 100:
        return "too_short"
    if str(meta.get("autogenerated", "False")) == "True" or AUTOGEN.search(text[:500]):
        return "autogenerated"
    lines = text.split("\n")
    if max(len(ln) for ln in lines) > 1000:
        return "max_line_len"
    if sum(len(ln) for ln in lines) / max(len(lines), 1) > 100:
        return "mean_line_len"
    alpha = sum(c.isalpha() for c in text) / n
    if alpha < 0.25:
        return "low_alpha_ratio"
    if text.count("\\x") / n > 0.01 or "base64," in text:
        return "encoded_data"
    return None
