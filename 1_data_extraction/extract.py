"""Stage 1 — Data extraction.

Streams raw text from the Hugging Face Hub (no full downloads; the disk is 92%
full) into Parquet shards, one process per source. Pre-training mix follows
Lecture 3 (web, code, math, encyclopaedic); a separate higher-quality pool is
reserved for mid-training. Post-training and evaluation sets are saved as JSONL.
"""
import ast
import json
import os
import sys
import time
from multiprocessing import Process

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from common.config import RAW_DIR, SMOKE, stage_dir  # noqa: E402
from common.logger import save_json, load_json, p  # noqa: E402
from common.energy import EnergyMeter  # noqa: E402

GB = 1e9
SCALE = 2e-3 if SMOKE else 1.0   # smoke: ~25 MB total

# name -> (hf path, config, split, text field, pretrain bytes, mid bytes, mid predicate)
SOURCES = {
    "web":  ("HuggingFaceFW/fineweb-edu", "sample-10BT", "train", "text", 8.6 * GB, 0.55 * GB,
             lambda ex: int(ex.get("int_score") or 0) >= 4),
    "code": ("codeparrot/codeparrot-clean", None, "train", "content", 1.4 * GB, 0.20 * GB,
             lambda ex: '"""' in ex["content"] and float(ex.get("alpha_frac") or 0) > 0.5),
    "math": ("HuggingFaceTB/finemath", "finemath-3plus", "train", "text", 0.9 * GB, 0.0, None),
    "math_hq": ("HuggingFaceTB/finemath", "finemath-4plus", "train", "text", 0.0, 0.30 * GB, lambda ex: True),
    "wiki": ("wikimedia/wikipedia", "20231101.en", "train", "text", 0.6 * GB, 0.20 * GB,
             lambda ex: len(ex["text"]) > 20000),
}
META_KEYS = ("int_score", "score", "url", "path", "alpha_frac", "autogenerated", "line_max", "title")


def write_shard(rows, path):
    import pyarrow as pa
    import pyarrow.parquet as pq
    tbl = pa.table({"text": [r[0] for r in rows], "meta": [json.dumps(r[1]) for r in rows]})
    pq.write_table(tbl, path + ".tmp", compression="zstd")
    os.replace(path + ".tmp", path)


def extract_source(name):
    from datasets import load_dataset
    hf, cfg, split, field, pre_b, mid_b, mid_pred = SOURCES[name]
    pre_b, mid_b = pre_b * SCALE, mid_b * SCALE
    out = os.path.join(RAW_DIR, name)
    os.makedirs(out, exist_ok=True)
    done = os.path.join(out, "_done.json")
    if os.path.exists(done):
        return
    ds = load_dataset(hf, cfg, split=split, streaming=True)
    if name in ("wiki", "code"):
        ds = ds.shuffle(seed=0, buffer_size=10000)   # wiki is alphabetical, code is grouped by repo
    shard_bytes = 2e6 if SMOKE else 200e6
    stats = {"docs_seen": 0, "pre_docs": 0, "pre_bytes": 0, "mid_docs": 0, "mid_bytes": 0}
    buf = {"pre": [], "mid": []}
    nb = {"pre": 0, "mid": 0}
    shard_i = {"pre": 0, "mid": 0}
    t0 = time.time()

    def flush(kind):
        if buf[kind]:
            write_shard(buf[kind], os.path.join(out, f"{kind}_{shard_i[kind]:04d}.parquet"))
            shard_i[kind] += 1
            buf[kind], nb[kind] = [], 0

    for ex in ds:
        text = ex.get(field)
        if not text:
            continue
        stats["docs_seen"] += 1
        meta = {k: ex[k] for k in META_KEYS if k in ex}
        meta["source"] = name
        size = len(text.encode("utf-8", "ignore"))
        if mid_pred is not None and stats["mid_bytes"] < mid_b and mid_pred(ex):
            kind = "mid"
        elif stats["pre_bytes"] < pre_b:
            kind = "pre"
        else:
            kind = None
        if kind:
            buf[kind].append((text, meta))
            nb[kind] += size
            stats[f"{kind}_docs"] += 1
            stats[f"{kind}_bytes"] += size
            if nb[kind] >= shard_bytes:
                flush(kind)
        if stats["pre_bytes"] >= pre_b and stats["mid_bytes"] >= mid_b:
            break
        if stats["docs_seen"] % 200000 == 0:
            p(f"{name}: {stats['docs_seen']} docs, pre {stats['pre_bytes']/GB:.2f} GB, "
              f"mid {stats['mid_bytes']/GB:.2f} GB, {(time.time()-t0)/60:.1f} min")
    flush("pre")
    flush("mid")
    stats["seconds"] = round(time.time() - t0, 1)
    stats["hf"] = hf
    stats["config"] = cfg
    save_json(done, stats)
    p(f"{name} done: {stats}")


# ---------------------------------------------------------------- post-training + eval sets
def _msgs(x):
    return ast.literal_eval(x) if isinstance(x, str) else x


def save_jsonl(path, rows):
    with open(path + ".tmp", "w") as f:
        for r in rows:
            f.write(json.dumps(r) + "\n")
    os.replace(path + ".tmp", path)


def extract_aux():
    from datasets import load_dataset
    out = os.path.join(RAW_DIR, "aux")
    os.makedirs(out, exist_ok=True)
    if os.path.exists(os.path.join(out, "_done.json")):
        return
    n_chat = 2000 if SMOKE else 250000
    stats = {}

    def take(hf, cfg, split, n=None):
        ds = load_dataset(hf, cfg, split=split, streaming=True)
        rows = []
        for i, ex in enumerate(ds):
            if n is not None and i >= n:
                break
            rows.append(ex)
        return rows

    # SFT chat
    rows = [{"messages": _msgs(r["messages"]), "source": r.get("source")}
            for r in take("HuggingFaceTB/smol-smoltalk", None, "train", n_chat)]
    save_jsonl(os.path.join(out, "sft_chat.jsonl"), rows); stats["sft_chat"] = len(rows)
    # SFT code
    rows = []
    for r in take("iamtarun/python_code_instructions_18k_alpaca", None, "train", 500 if SMOKE else None):
        u = r["instruction"] + (("\n\nInput: " + r["input"]) if r["input"] else "")
        rows.append({"messages": [{"role": "user", "content": u}, {"role": "assistant", "content": r["output"]}],
                     "source": "python_alpaca"})
    save_jsonl(os.path.join(out, "sft_code.jsonl"), rows); stats["sft_code"] = len(rows)
    # preferences
    for split, name in (("train_prefs", "pref_train"), ("test_prefs", "pref_test")):
        rows = []
        for r in take("HuggingFaceH4/ultrafeedback_binarized", None, split, 1000 if SMOKE else None):
            c, rj = _msgs(r["chosen"]), _msgs(r["rejected"])
            if float(r["score_chosen"]) <= float(r["score_rejected"]):
                continue
            rows.append({"prompt": r["prompt"], "chosen": c[-1]["content"], "rejected": rj[-1]["content"],
                         "score_chosen": float(r["score_chosen"]), "score_rejected": float(r["score_rejected"])})
        save_jsonl(os.path.join(out, f"{name}.jsonl"), rows); stats[name] = len(rows)
    # evaluation sets (full; small)
    evals = {
        "hellaswag": ("Rowan/hellaswag", None, "validation"),
        "arc_easy": ("allenai/ai2_arc", "ARC-Easy", "test"),
        "piqa": ("baber/piqa", None, "validation"),
        "lambada": ("EleutherAI/lambada_openai", "default", "test"),
        "humaneval": ("openai/openai_humaneval", None, "test"),
        "mbpp": ("google-research-datasets/mbpp", "full", "test"),
        "gsm8k": ("openai/gsm8k", "main", "test"),
        "gsm8k_train": ("openai/gsm8k", "main", "train"),
    }
    for name, (hf, cfg, split) in evals.items():
        rows = take(hf, cfg, split)
        save_jsonl(os.path.join(out, f"eval_{name}.jsonl"), rows); stats[f"eval_{name}"] = len(rows)
    save_json(os.path.join(out, "_done.json"), stats)
    p(f"aux done: {stats}")


def main():
    out = stage_dir("1_data_extraction")
    meter = EnergyMeter(out).start()
    t0 = time.time()
    procs = [Process(target=extract_source, args=(n,)) for n in SOURCES] + [Process(target=extract_aux)]
    for pr in procs:
        pr.start()
    for pr in procs:
        pr.join()
    summary = {"sources": {}, "aux": load_json(os.path.join(RAW_DIR, "aux", "_done.json"), {})}
    for n in SOURCES:
        summary["sources"][n] = load_json(os.path.join(RAW_DIR, n, "_done.json"), {})
    missing = [n for n, s in summary["sources"].items() if not s] + ([] if summary["aux"] else ["aux"])
    summary["seconds"] = round(time.time() - t0, 1)
    summary["energy"] = meter.stop()
    save_json(os.path.join(out, "summary.json"), summary)
    if missing:
        raise SystemExit(f"extraction failed for {missing}")
    tot = sum(s["pre_bytes"] for s in summary["sources"].values()) / GB
    p(f"Stage 1 done: {tot:.2f} GB pre-train raw text")


if __name__ == "__main__":
    main()
